#!/usr/bin/env python3
"""Validate layered requirements lockfile generation contract (ADR-032).

This validator enforces the following contracts:
1. All checked-in lockfiles must be generated with the expected Python version
2. Checked-in ML lockfiles are limited to the supported Apple Silicon target-owned contract
3. Non-core optional and retired unsupported ML lockfiles must not be checked in
4. Darwin arm64 ML inputs must preserve the supported security baseline
5. Known-bad runtime combinations must be rejected in lockfiles
6. The lock ownership manifest must cover every governed checked-in lock exactly once
7. Generic lockfiles must retain platform-marked core runtime packages declared in base.in

CONTRACT SEPARATION:
- Target-owned ML lockfiles: ml-core-darwin-arm64
- Non-core optional ML layers are not part of the checked-in lockfile contract
- Scripted-only layers: ml-sam2 (requires non-standard install semantics)

TARGET MATRIX (ADR-032):
- Target-owned ML lockfiles:
  - ml-core-darwin-arm64.txt (macOS Apple Silicon secure baseline)
- Retired unsupported Linux and macOS Intel lockfiles must remain absent from
  the installable requirements surface.
- Non-core optional ML lockfiles must be absent from the checked-in repository state
- Target-owned ML core lockfiles must not carry the wrong OS markers

Scripted-only layers are NOT validated as standard lockfile contracts.
They exist for documentation but install path is via bootstrap script.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from check_dependency_pinning import find_violations
from check_lock_ownership import load_lock_ownership, validate_manifest_contract

REPO_ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS_DIR = REPO_ROOT / "requirements"
MAKEFILE_PATH = REQUIREMENTS_DIR / "Makefile"
LOCK_OWNERSHIP_PATH = REQUIREMENTS_DIR / "lock_ownership.yml"

# Core lockfiles that must always exist
CORE_LOCK_FILES = (
    "all.txt",
    "base.txt",
    "dev.txt",
    "ci.txt",
    "security.txt",
    "tools-archive.txt",
)

# Target-owned ML core lockfiles (pip-compile multi-platform fix)
PLATFORM_ML_CORE_LOCK_FILES = ("ml-core-darwin-arm64.txt",)
GOVERNED_LOCK_FILES = CORE_LOCK_FILES + PLATFORM_ML_CORE_LOCK_FILES

# Non-core optional ML lockfiles are not part of the checked-in contract.
# If they appear in the repository state, validation fails so accidental
# host-generated artifacts do not silently re-enter the tree.
NONCORE_OPTIONAL_ML_LOCK_FILES = (
    "ml-core.txt",
    "ml-cpu.txt",
    "ml-mps.txt",
    "ml-cuda.txt",
    "ml-raw.txt",
    "ml-coreml.txt",
    "ml-research.txt",
    "ml.txt",
)
RETIRED_UNSUPPORTED_ML_REQUIREMENT_FILES = (
    "ml-core-darwin-x86_64.in",
    "ml-core-darwin-x86_64.txt",
    "ml-core-linux.in",
    "ml-core-linux.txt",
)

# Scripted-only ML layers (NOT standard lockfile contract)
# These require non-standard install semantics via bootstrap script
SCRIPTED_ONLY_ML_LAYERS = ("ml-sam2.txt",)

# All lockfiles for header validation (includes scripted for consistency checking)
ALL_LOCK_FILES = GOVERNED_LOCK_FILES + SCRIPTED_ONLY_ML_LAYERS
PLATFORM_LOCK_FORBIDDEN_PATTERNS = {
    "ml-core-darwin-arm64.txt": (
        r"""platform_system\s*==\s*["']Linux["']""",
        r"""platform_system\s*!=\s*["']Darwin["']""",
    ),
}
LOCK_VERSION_PATTERN = re.compile(r"^LOCK_PYTHON_VERSION\s+\?=\s+([0-9.]+)\s*$")
HEADER_PATTERN = re.compile(r"^# This file is autogenerated by pip-compile with Python ([0-9.]+)$")
PACKAGE_PIN_PATTERN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;#]+)")
NUMERIC_VERSION_PATTERN = re.compile(r"\d+")
REQUIREMENT_NAME_PATTERN = re.compile(r"^([A-Za-z0-9_.-]+)")

DARWIN_ARM64_COREML_PATTERN = re.compile(r"^coremltools\b[^\n]*$", re.IGNORECASE)
DARWIN_LOCKFILE_FORBIDDEN_PACKAGES = ("triton",)
DARWIN_LOCKFILE_FORBIDDEN_PREFIXES = ("nvidia-",)
GENERIC_LINUX_KEYRING_REQUIRED_PACKAGES = {
    "all.txt": ("jeepney", "secretstorage"),
    "ci.txt": ("cffi", "cryptography", "jeepney", "pycparser", "secretstorage"),
}
GENERIC_BASE_RUNTIME_PLATFORM_MARKER_PACKAGES = (
    ("opencv-python", re.compile(r"""platform_system\s*!=\s*["']Linux["']"""), 'platform_system != "Linux"'),
    ("opencv-python-headless", re.compile(r"""platform_system\s*==\s*["']Linux["']"""), 'platform_system == "Linux"'),
)
GENERIC_BASE_RUNTIME_LOCKS = ("all.txt", "base.txt")
# Note: [^\n]* (not [^#\n]*) intentionally matches lines that carry inline comments,
# because ml-core-darwin-arm64.in declares coremltools with a trailing # comment.
# The x86 guard patterns check stripped non-comment lines, so they use [^#\n]*.

SUPPORTED_TORCH_PIN = "2.13.0"
SUPPORTED_TORCHVISION_PIN = "0.28.0"
SUPPORTED_DIFFUSERS_MIN = "0.38.0"
SUPPORTED_DIFFUSERS_INPUT_RANGE = "diffusers>=0.38.0,<1"
SUPPORTED_TRANSFORMERS_MIN = "5.5.0"
SUPPORTED_TRANSFORMERS_INPUT_RANGE = "transformers>=5.5.0,<5.6"


def read_expected_lock_python_version() -> str:
    """Return the lockfile Python version declared in requirements/Makefile."""
    for line in MAKEFILE_PATH.read_text(encoding="utf-8").splitlines():
        match = LOCK_VERSION_PATTERN.match(line)
        if match:
            return match.group(1)
    raise ValueError(f"Could not determine LOCK_PYTHON_VERSION from {MAKEFILE_PATH}")


def validate_lockfile_headers(
    expected_python: str,
    *,
    requirements_dir: Path | None = None,
    lock_files: tuple[str, ...] | None = None,
) -> list[str]:
    """Return header validation errors for generated lockfiles.

    Only validates files that exist. ML layer lockfiles may not exist in
    environments where they haven't been compiled yet (e.g., fresh checkouts).

    Contract separation:
    - Platform-specific ML core layers: optional during transition
    - Standard ML layers: validated as optional during transition
    - Scripted-only layers: validated if present but not required
    """
    errors: list[str] = []
    target_dir = REQUIREMENTS_DIR if requirements_dir is None else requirements_dir
    target_locks = ALL_LOCK_FILES if lock_files is None else lock_files
    for lock_name in target_locks:
        lock_path = target_dir / lock_name
        if not lock_path.is_file():
            # Scripted-only layers are not required as lockfiles
            if lock_name in SCRIPTED_ONLY_ML_LAYERS:
                # Silently skip - scripted-only layers may not have lockfiles
                continue
            errors.append(f"Missing required lockfile: {lock_path}")
            continue

        header_match = None
        for line in lock_path.read_text(encoding="utf-8").splitlines()[:5]:
            header_match = HEADER_PATTERN.match(line)
            if header_match:
                break

        if header_match is None:
            errors.append(f"Missing pip-compile Python header in {lock_path}")
            continue

        actual_python = header_match.group(1)
        if actual_python != expected_python:
            errors.append(f"{lock_path} was generated with Python {actual_python}; " f"expected Python {expected_python}")

    return errors


def validate_noncore_optional_lockfiles_absent() -> list[str]:
    """Return errors when non-core optional ML lockfiles are checked in."""
    errors: list[str] = []

    for lock_name in NONCORE_OPTIONAL_ML_LOCK_FILES:
        ml_lock_path = REQUIREMENTS_DIR / lock_name
        if ml_lock_path.is_file():
            errors.append(
                f"{ml_lock_path} is not part of the checked-in lockfile contract; "
                "remove host-generated non-core ML layer artifacts from the repository"
            )
    return errors


def validate_retired_unsupported_ml_requirement_files_absent() -> list[str]:
    """Return errors when retired unsupported ML manifests re-enter requirements/."""
    errors: list[str] = []

    for requirement_name in RETIRED_UNSUPPORTED_ML_REQUIREMENT_FILES:
        requirement_path = REQUIREMENTS_DIR / requirement_name
        if requirement_path.is_file():
            errors.append(
                f"{requirement_path} is a retired unsupported ML manifest; keep historical "
                "Linux/macOS Intel lane details in docs, not in scan-visible requirements files"
            )
    return errors


def validate_platform_lock_markers() -> list[str]:
    """Ensure platform-specific ML lockfiles do not carry the wrong OS markers."""
    errors: list[str] = []

    for lock_name, forbidden_patterns in PLATFORM_LOCK_FORBIDDEN_PATTERNS.items():
        ml_lock_path = REQUIREMENTS_DIR / lock_name
        if not ml_lock_path.is_file():
            continue

        for line_number, raw_line in enumerate(ml_lock_path.read_text(encoding="utf-8").splitlines(), start=1):
            line = raw_line.strip()
            if not line or line.startswith("#"):
                continue
            for pattern in forbidden_patterns:
                if re.search(pattern, line):
                    errors.append(
                        f"{ml_lock_path}:{line_number} contains forbidden platform marker pattern {pattern!r} "
                        "for this target lockfile"
                    )
    return errors


def validate_ml_layer_structure() -> list[str]:
    """Validate that ML layer .in files exist for the layered strategy.

    Standard, retired-stub, and scripted-only .in files should exist for
    documentation, but only supported checked-in locks follow the install
    support contract.

    Platform matrix (ADR-032):
    - Platform-specific core: ml-core-darwin-arm64.in
    - Acceleration/stub layers: ml-cpu.in, ml-mps.in, ml-cuda.in
    - Capability layers: ml-raw.in, ml-coreml.in, ml-research.in
    """
    errors: list[str] = []
    # Platform-specific lockfile layers (must exist)
    platform_in_files = [
        "ml-core-darwin-arm64.in",
    ]
    # Standard/stub layer inputs (must exist; not all produce supported locks)
    standard_in_files = [
        "ml-core.in",
        "ml-cpu.in",
        "ml-mps.in",
        "ml-cuda.in",
        "ml-raw.in",
        "ml-coreml.in",
        "ml-research.in",
    ]
    # Scripted-only layers (should exist for documentation)
    scripted_in_files = [
        "ml-sam2.in",
    ]
    for in_file in platform_in_files + standard_in_files + scripted_in_files:
        in_path = REQUIREMENTS_DIR / in_file
        if not in_path.is_file():
            errors.append(f"Missing ML layer input file: {in_path}")
    return errors


def validate_lock_ownership_manifest() -> list[str]:
    """Ensure the lock ownership manifest covers the governed lock surface."""
    try:
        manifest = load_lock_ownership(LOCK_OWNERSHIP_PATH)
    except ValueError as exc:
        return [str(exc)]

    return validate_manifest_contract(
        manifest,
        governed_lock_files=GOVERNED_LOCK_FILES,
    )


def _normalize_package_name(name: str) -> str:
    return name.strip().lower().replace("_", "-")


def _parse_numeric_version(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in NUMERIC_VERSION_PATTERN.findall(version))


def _has_exact_pin(lines: list[str], package_name: str, version: str) -> bool:
    pattern = re.compile(rf"^{re.escape(package_name)}\s*==\s*{re.escape(version)}(?:\s|$)", re.IGNORECASE)
    return any(pattern.search(line) for line in lines)


def _read_pinned_packages(lock_path: Path) -> dict[str, str]:
    packages: dict[str, str] = {}
    for raw_line in lock_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        match = PACKAGE_PIN_PATTERN.match(line)
        if match:
            packages[_normalize_package_name(match.group(1))] = match.group(2)
    return packages


def _input_declares_package_with_marker(input_path: Path, package_name: str, marker_pattern: re.Pattern[str]) -> bool:
    normalized_package_name = _normalize_package_name(package_name)
    for raw_line in input_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if not line or line.startswith("-r") or ";" not in line:
            continue

        requirement_text, marker_text = (part.strip() for part in line.split(";", 1))
        match = REQUIREMENT_NAME_PATTERN.match(requirement_text)
        if match is None:
            continue
        if _normalize_package_name(match.group(1)) != normalized_package_name:
            continue
        if marker_pattern.search(marker_text):
            return True
    return False


def validate_generic_base_runtime_platform_marker_pins(
    requirements_dir: Path | None = None,
) -> list[str]:
    """Ensure generic locks retain platform-marked base runtime packages."""
    target_dir = REQUIREMENTS_DIR if requirements_dir is None else requirements_dir
    base_input_path = target_dir / "base.in"
    if not base_input_path.is_file():
        return []

    errors: list[str] = []
    declared_packages = {
        package_name: marker_description
        for package_name, marker_pattern, marker_description in GENERIC_BASE_RUNTIME_PLATFORM_MARKER_PACKAGES
        if _input_declares_package_with_marker(base_input_path, package_name, marker_pattern)
    }
    if not declared_packages:
        return errors

    for lock_name in GENERIC_BASE_RUNTIME_LOCKS:
        lock_path = target_dir / lock_name
        if not lock_path.is_file():
            continue

        packages = _read_pinned_packages(lock_path)
        for package_name, marker_description in declared_packages.items():
            if package_name in packages:
                continue
            errors.append(
                f"{lock_path} must retain {package_name!r} because {base_input_path} declares it with marker "
                f"{marker_description!r}. Regenerate the generic lock on ubuntu-x64-generic or restore the pinned "
                "platform-marked runtime dependency."
            )

    return errors


def validate_generic_linux_keyring_pins(requirements_dir: Path | None = None) -> list[str]:
    """Ensure generic locks keep the Linux keyring backend pinned."""
    errors: list[str] = []
    target_dir = REQUIREMENTS_DIR if requirements_dir is None else requirements_dir

    for lock_name, required_packages in GENERIC_LINUX_KEYRING_REQUIRED_PACKAGES.items():
        lock_path = target_dir / lock_name
        if not lock_path.is_file():
            continue

        packages = _read_pinned_packages(lock_path)
        if "keyring" not in packages:
            continue

        missing = [package for package in required_packages if package not in packages]
        if missing:
            missing_text = ", ".join(repr(package) for package in missing)
            errors.append(
                f"{lock_path} pins keyring=={packages['keyring']} but is missing Linux keyring-chain packages "
                f"{missing_text}. Regenerate the generic lock on ubuntu-x64-generic or restore the pinned "
                "Linux transitive dependencies explicitly."
            )

    return errors


def validate_staged_generic_lock_contract(staging_dir: Path, expected_python: str) -> list[str]:
    """Validate the complete staged generic set before any live replacement."""
    lock_paths = [staging_dir / lock_name for lock_name in CORE_LOCK_FILES]
    errors = validate_lockfile_headers(
        expected_python,
        requirements_dir=staging_dir,
        lock_files=CORE_LOCK_FILES,
    )
    errors.extend(validate_generic_base_runtime_platform_marker_pins(staging_dir))
    errors.extend(validate_generic_linux_keyring_pins(staging_dir))
    errors.extend(find_violations(lock_paths))
    return errors


def validate_darwin_lock_purity() -> list[str]:
    """Fail if Darwin lockfiles contain Linux/CUDA-only packages."""
    errors: list[str] = []

    for lock_name in ("ml-core-darwin-arm64.txt",):
        lock_path = REQUIREMENTS_DIR / lock_name
        if not lock_path.is_file():
            continue

        for package_name in sorted(_read_pinned_packages(lock_path)):
            if package_name in DARWIN_LOCKFILE_FORBIDDEN_PACKAGES or any(
                package_name.startswith(prefix) for prefix in DARWIN_LOCKFILE_FORBIDDEN_PREFIXES
            ):
                errors.append(
                    f"{lock_path} contains forbidden Darwin package {package_name!r}. "
                    "Darwin platform-core lockfiles must not contain Linux/CUDA-only packages."
                )

    return errors


def _normalized_lock_body(lock_path: Path) -> tuple[str, ...]:
    lines: list[str] = []
    for raw_line in lock_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        lines.append(line)
    return tuple(lines)


def validate_darwin_input_guards() -> list[str]:
    """Ensure Darwin arm64 ML input preserves the supported security baseline."""
    errors: list[str] = []
    darwin_arm64_input = REQUIREMENTS_DIR / "ml-core-darwin-arm64.in"
    if not darwin_arm64_input.is_file():
        return errors

    arm64_non_comment_lines = [
        line.strip()
        for line in darwin_arm64_input.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    if not _has_exact_pin(arm64_non_comment_lines, "torch", SUPPORTED_TORCH_PIN):
        errors.append(
            f"{darwin_arm64_input} must pin torch=={SUPPORTED_TORCH_PIN} for the supported Apple Silicon security baseline."
        )
    if not _has_exact_pin(arm64_non_comment_lines, "torchvision", SUPPORTED_TORCHVISION_PIN):
        errors.append(
            f"{darwin_arm64_input} must pin torchvision=={SUPPORTED_TORCHVISION_PIN} alongside the supported Apple Silicon torch baseline."
        )
    if SUPPORTED_DIFFUSERS_INPUT_RANGE not in arm64_non_comment_lines:
        errors.append(
            f"{darwin_arm64_input} must declare {SUPPORTED_DIFFUSERS_INPUT_RANGE!r} for the supported Diffusers security baseline."
        )
    if SUPPORTED_TRANSFORMERS_INPUT_RANGE not in arm64_non_comment_lines:
        errors.append(
            f"{darwin_arm64_input} must declare {SUPPORTED_TRANSFORMERS_INPUT_RANGE!r} for the supported Transformers security baseline."
        )
    if not any(DARWIN_ARM64_COREML_PATTERN.search(line) for line in arm64_non_comment_lines):
        errors.append(
            f"{darwin_arm64_input} must declare coremltools so Apple Silicon CoreML support "
            "is part of the arm64 ML baseline contract."
        )
    return errors


def validate_platform_lock_divergence() -> list[str]:
    """Retained for API compatibility; there is only one active ML lock lane."""
    return []


def validate_platform_lock_runtime_compatibility() -> list[str]:
    """Reject known-bad platform lock combinations before runtime."""
    errors: list[str] = []

    for lock_name in PLATFORM_ML_CORE_LOCK_FILES:
        lock_path = REQUIREMENTS_DIR / lock_name
        if not lock_path.is_file():
            continue

        packages = _read_pinned_packages(lock_path)
        torch_version = packages.get("torch")
        torchvision_version = packages.get("torchvision")
        diffusers_version = packages.get("diffusers")
        transformers_version = packages.get("transformers")

        if lock_name == "ml-core-darwin-arm64.txt" and "coremltools" not in packages:
            errors.append(
                f"{lock_path} must include a pinned coremltools dependency so Apple Silicon "
                "CoreML support remains part of the checked-in arm64 contract."
            )
        if lock_name == "ml-core-darwin-arm64.txt" and "diffusers" not in packages:
            errors.append(
                f"{lock_path} must include a pinned diffusers dependency so the supported Diffusers "
                "security baseline remains part of the checked-in arm64 contract."
            )

        if (
            lock_name == "ml-core-darwin-arm64.txt"
            and torch_version is not None
            and _parse_numeric_version(torch_version) < _parse_numeric_version(SUPPORTED_TORCH_PIN)
        ):
            errors.append(
                f"{lock_path} must rotate to torch=={SUPPORTED_TORCH_PIN} for the supported Apple Silicon security baseline."
            )
        if (
            lock_name == "ml-core-darwin-arm64.txt"
            and torchvision_version is not None
            and _parse_numeric_version(torchvision_version) < _parse_numeric_version(SUPPORTED_TORCHVISION_PIN)
        ):
            errors.append(
                f"{lock_path} must rotate to torchvision=={SUPPORTED_TORCHVISION_PIN} for the supported Apple Silicon security baseline."
            )
        if (
            lock_name == "ml-core-darwin-arm64.txt"
            and diffusers_version is not None
            and _parse_numeric_version(diffusers_version) < _parse_numeric_version(SUPPORTED_DIFFUSERS_MIN)
        ):
            errors.append(
                f"{lock_path} must rotate to diffusers>={SUPPORTED_DIFFUSERS_MIN} for the supported Diffusers security baseline."
            )
        if (
            lock_name == "ml-core-darwin-arm64.txt"
            and transformers_version is not None
            and _parse_numeric_version(transformers_version) < _parse_numeric_version(SUPPORTED_TRANSFORMERS_MIN)
        ):
            errors.append(
                f"{lock_path} must rotate to transformers>={SUPPORTED_TRANSFORMERS_MIN} for the supported Transformers security baseline."
            )
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--staged-generic-dir",
        type=Path,
        help="Validate only a staged six-file generic lock set before publication",
    )
    parser.add_argument(
        "--expected-python",
        help="Expected pip-compile Python header for --staged-generic-dir",
    )
    args = parser.parse_args()

    errors: list[str] = []

    try:
        expected_python = read_expected_lock_python_version()
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.staged_generic_dir is not None:
        expected_staged_python = args.expected_python or expected_python
        errors.extend(validate_staged_generic_lock_contract(args.staged_generic_dir, expected_staged_python))
        if errors:
            print("ERROR: staged generic requirements lock validation failed:", file=sys.stderr)
            for error in errors:
                print(f"  - {error}", file=sys.stderr)
            return 1
        print(
            "staged generic requirements lock contract passed: "
            f"{len(CORE_LOCK_FILES)} locks verified for Python {expected_staged_python}"
        )
        return 0

    errors.extend(validate_ml_layer_structure())
    errors.extend(validate_lock_ownership_manifest())
    errors.extend(validate_lockfile_headers(expected_python))
    errors.extend(validate_noncore_optional_lockfiles_absent())
    errors.extend(validate_retired_unsupported_ml_requirement_files_absent())
    errors.extend(validate_generic_base_runtime_platform_marker_pins())
    errors.extend(validate_generic_linux_keyring_pins())
    errors.extend(validate_platform_lock_markers())
    errors.extend(validate_darwin_input_guards())
    errors.extend(validate_platform_lock_divergence())
    errors.extend(validate_darwin_lock_purity())
    errors.extend(validate_platform_lock_runtime_compatibility())

    if errors:
        print("ERROR: requirements lock contract validation failed:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1

    print(
        f"requirements lock contract passed: headers match "
        f"Python {expected_python}, target-owned ML lockfiles and ownership manifest verified."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
