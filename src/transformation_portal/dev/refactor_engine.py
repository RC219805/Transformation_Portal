"""Auto-refactoring engine for semantic code deduplication.

This module provides a closed-loop code optimizer that:
- Detects duplicate semantic code via AST hashing
- Selects canonical implementations
- Extracts to shared modules
- Rewrites imports and call sites
- Enforces semantic reuse

Pipeline:
    SCAN → HASH → GROUP → SELECT CANONICAL → EXTRACT → REWRITE → VALIDATE

This is effectively a compiler pass + linker for the repository,
ensuring minimal representation and enforced reuse.

Usage:
    from transformation_portal.dev.refactor_engine import AutoRefactorEngine

    engine = AutoRefactorEngine(
        root=Path("src"),
        shared_module=Path("src/transformation_portal/shared"),
    )

    plan = engine.build_plan()
    print(f"Found {len(plan.duplicates)} duplicate groups")

    # Execute refactoring (with dry_run for safety)
    result = engine.execute(plan, dry_run=True)

Safety contract of a real (non dry-run) execution:
    - each shared module is a verbatim copy of its canonical file behind a
      comment header, and it must compile, keep the group's AST hash and import
      cleanly (in a subprocess) with every name the stubs re-export before any
      duplicate is rewritten;
    - duplicates are rewritten to stubs that re-export every top-level name by
      explicit import, so private names and star imports keep working;
    - groups whose module cannot be relocated safely (relative imports,
      ``__file__``, conditional top-level bindings, star imports, ...) or that
      have fewer than ``min_symbols`` top-level symbols are skipped;
    - any failure marks the result as failed and rolls the tree back: created
      files are removed and rewritten files are restored from their backups.
"""

from __future__ import annotations

import ast
import logging
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator, Optional

from transformation_portal.dev.ast_hash import compute_ast_hash, compute_function_hash
from transformation_portal.dev.ast_index import ASTEquivalenceIndex

logger = logging.getLogger(__name__)

_STUB_MARKER = "# Auto-generated by AutoRefactorEngine: re-exports the canonical shared module."
"""First line of every generated re-export stub (used to keep re-runs idempotent)."""

_CODING_COOKIE_RE = re.compile(r"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+")
"""PEP 263 encoding declaration; it must stay on line 1 or 2 of a module."""

_LOCATION_DUNDERS = frozenset({"__file__", "__path__", "__spec__", "__loader__", "__package__", "__cached__"})
"""Module globals whose values change when a module is moved to the shared package."""

_IMPORT_CHECK_TIMEOUT_S = 120.0
"""Upper bound for importing the generated shared modules in a subprocess."""

_IMPORT_CHECK_PREFIX = "REFACTOR-IMPORT-CHECK: "

# Runs in a fresh interpreter: imports every generated shared module and checks
# that each name the stubs will re-export exists. Reads one
# "<dotted.module>=<name>,<name>" spec per stdin line.
_IMPORT_CHECK_SCRIPT = f"""\
import importlib
import sys

sys.path.insert(0, sys.argv[1])
failures = []
for spec in sys.stdin.read().splitlines():
    module_name, _, names = spec.partition("=")
    try:
        module = importlib.import_module(module_name)
    except BaseException as exc:
        failures.append(module_name + ": import failed: " + type(exc).__name__ + ": " + str(exc))
        continue
    missing = [name for name in names.split(",") if name and not hasattr(module, name)]
    if missing:
        failures.append(module_name + ": missing names: " + ", ".join(missing))
for failure in failures:
    print("{_IMPORT_CHECK_PREFIX}" + failure, file=sys.stderr)
sys.exit(1 if failures else 0)
"""


def _target_names(target: ast.expr) -> Iterator[str]:
    """Yield the module-level names bound by an assignment target."""
    if isinstance(target, ast.Name):
        yield target.id
    elif isinstance(target, (ast.Tuple, ast.List)):
        for element in target.elts:
            yield from _target_names(element)
    elif isinstance(target, ast.Starred):
        yield from _target_names(target.value)
    # Attribute and subscript targets bind no module-level name.


def _is_type_checking_block(stmt: ast.stmt) -> bool:
    """Return True for ``if TYPE_CHECKING:`` without an else branch (binds nothing at runtime)."""
    if not isinstance(stmt, ast.If) or stmt.orelse:
        return False
    test = stmt.test
    return (isinstance(test, ast.Name) and test.id == "TYPE_CHECKING") or (
        isinstance(test, ast.Attribute) and test.attr == "TYPE_CHECKING"
    )


def _relocation_blocker(tree: ast.Module) -> Optional[str]:
    """Return why a module cannot be moved and re-exported by name, or None when it can.

    A module can only be replaced by a stub that imports its names from a
    relocated copy when its top-level bindings are static and unconditional and
    nothing in it depends on where the module lives.
    """
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.level:
            return "relative import (resolves differently once moved)"
        if isinstance(node, ast.Name) and node.id in _LOCATION_DUNDERS:
            return f"uses {node.id} (changes once moved)"
        # A stub binds copies of the shared module's globals at import time, so
        # later rebinding in the shared module is invisible through the stub.
        if isinstance(node, ast.Global):
            return "global statement (rebinding is invisible through the re-export stub)"
        if isinstance(node, ast.Name) and node.id == "globals":
            return "uses globals() (bindings are not static)"

    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Import, ast.Pass)):
            continue
        if isinstance(stmt, ast.ImportFrom):
            if any(alias.name == "*" for alias in stmt.names):
                return "star import (exported names are not static)"
            continue
        if _is_type_checking_block(stmt):
            continue
        if isinstance(stmt, (ast.Expr, ast.Assign, ast.AnnAssign, ast.AugAssign, ast.Assert, ast.Raise)):
            if any(isinstance(node, ast.NamedExpr) for node in ast.walk(stmt)):
                return "top-level assignment expression (bindings are not static)"
            continue
        return f"top-level {type(stmt).__name__} statement (bindings are not static)"
    return None


def _module_exports(tree: ast.Module) -> list[str]:
    """Return every name a module binds at top level (``__future__`` features excluded).

    Only meaningful for modules without a relocation blocker, whose top-level
    bindings are static and unconditional.
    """
    names: set[str] = set()
    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(stmt.name)
        elif isinstance(stmt, ast.Import):
            for alias in stmt.names:
                names.add(alias.asname or alias.name.split(".")[0])
        elif isinstance(stmt, ast.ImportFrom):
            if _is_future_import(stmt):
                continue
            for alias in stmt.names:
                names.add(alias.asname or alias.name)
        elif isinstance(stmt, ast.Assign):
            for target in stmt.targets:
                names.update(_target_names(target))
        elif isinstance(stmt, ast.AnnAssign) and stmt.value is not None:
            names.update(_target_names(stmt.target))
        elif isinstance(stmt, ast.AugAssign):
            names.update(_target_names(stmt.target))
    return sorted(names)


def _is_future_import(stmt: ast.stmt) -> bool:
    return isinstance(stmt, ast.ImportFrom) and stmt.module == "__future__" and not stmt.level


@dataclass
class SymbolInfo:
    """Information about an extracted symbol."""

    name: str
    """Symbol name (function or class name)."""

    kind: str
    """Symbol kind: 'function', 'async_function', or 'class'."""

    hash: str
    """AST hash of the symbol."""

    source: str
    """Canonical source code of the symbol."""


@dataclass
class RefactorPlan:
    """Plan for refactoring duplicate code."""

    canonical_map: dict[str, Path] = field(default_factory=dict)
    """Map from AST hash to canonical file path."""

    duplicates: dict[str, list[Path]] = field(default_factory=dict)
    """Map from AST hash to list of duplicate file paths."""

    symbols: dict[str, list[SymbolInfo]] = field(default_factory=dict)
    """Map from AST hash to extracted symbols."""

    affected_files: set[Path] = field(default_factory=set)
    """Set of files that will be modified."""

    skipped: dict[str, str] = field(default_factory=dict)
    """Map from AST hash to the reason a duplicate group is left alone."""

    def summary(self) -> str:
        """Get a summary of the refactoring plan."""
        lines = [
            "Refactoring Plan",
            "=" * 50,
            f"Duplicate groups: {len(self.duplicates)}",
            f"Files to refactor: {len(self.affected_files)}",
            f"Symbols to extract: {sum(len(s) for s in self.symbols.values())}",
        ]
        if self.skipped:
            lines.append(f"Skipped groups: {len(self.skipped)}")

        if self.duplicates:
            lines.append("")
            lines.append("Duplicate Groups:")
            for hash_val, files in list(self.duplicates.items())[:5]:
                canonical = self.canonical_map.get(hash_val)
                lines.append(f"  Hash: {hash_val[:12]}")
                lines.append(f"    Canonical: {canonical}")
                for f in files[:3]:
                    lines.append(f"    Duplicate: {f}")
                if len(files) > 3:
                    lines.append(f"    ... and {len(files) - 3} more")

        return "\n".join(lines)


@dataclass
class RefactorResult:
    """Result of executing a refactoring plan."""

    success: bool
    """Whether refactoring completed successfully."""

    files_created: list[Path] = field(default_factory=list)
    """New files created in shared module."""

    files_modified: list[Path] = field(default_factory=list)
    """Files modified with new imports."""

    files_deleted: list[Path] = field(default_factory=list)
    """Files deleted (replaced with imports)."""

    errors: list[str] = field(default_factory=list)
    """Error messages for any failures."""

    dry_run: bool = False
    """Whether this was a dry run."""

    backups: dict[Path, bytes] = field(default_factory=dict)
    """Original bytes of every rewritten file, used by rollback."""

    dirs_created: list[Path] = field(default_factory=list)
    """Directories created for the shared module (deepest first)."""

    rolled_back: bool = False
    """Whether the changes of this execution have been rolled back."""

    def summary(self) -> str:
        """Get a summary of the refactoring result."""
        if self.dry_run:
            status = "DRY RUN"
        elif self.rolled_back:
            status = "ROLLED BACK" if self.success else "FAILED (rolled back)"
        else:
            status = "SUCCESS" if self.success else "FAILED"
        lines = [
            f"Refactoring Result: {status}",
            "=" * 50,
            f"Files created: {len(self.files_created)}",
            f"Files modified: {len(self.files_modified)}",
            f"Files deleted: {len(self.files_deleted)}",
        ]

        if self.errors:
            lines.append(f"Errors: {len(self.errors)}")
            for err in self.errors[:5]:
                lines.append(f"  - {err}")

        return "\n".join(lines)


class AutoRefactorEngine:
    """Semantic deduplication and refactoring engine.

    This engine implements a closed-loop optimizer that:
    1. Scans codebase for semantic duplicates
    2. Selects canonical implementations
    3. Extracts to shared modules
    4. Rewrites duplicates to import from shared
    5. Validates semantic equivalence

    Example:
        engine = AutoRefactorEngine(
            root=Path("src"),
            shared_module=Path("src/mypackage/shared"),
        )

        # Build plan (no modifications)
        plan = engine.build_plan()

        # Execute with dry run first
        result = engine.execute(plan, dry_run=True)

        # Execute for real
        result = engine.execute(plan, dry_run=False)
    """

    def __init__(
        self,
        root: Path,
        shared_module: Path,
        *,
        exclude_patterns: Optional[list[str]] = None,
        min_symbols: int = 1,
        package_name: Optional[str] = None,
    ):
        """Initialize the refactoring engine.

        Args:
            root: Root directory to scan for duplicates.
            shared_module: Directory for extracted shared modules.
            exclude_patterns: Glob patterns to exclude from scanning.
            min_symbols: Minimum number of symbols to consider a file for extraction.
            package_name: Package name for imports (auto-detected if not provided).
        """
        self.root = root
        self.shared_module = shared_module
        self.exclude_patterns = exclude_patterns or [
            "**/test_*.py",
            "**/*_test.py",
            "**/conftest.py",
            "**/__pycache__/**",
        ]
        self.min_symbols = min_symbols
        self.package_name = package_name or self._detect_package_name()

    def _detect_package_name(self) -> str:
        """Detect the package name from the shared module path."""
        # Convert path to module notation
        parts = self.shared_module.relative_to(self.root).parts
        return ".".join(parts)

    # --------------------------------------------------
    # Phase 1: Build refactoring plan
    # --------------------------------------------------
    def build_plan(self) -> RefactorPlan:
        """Build a refactoring plan by scanning for duplicates.

        Returns:
            RefactorPlan with canonical selections and duplicate mappings.
        """
        index = ASTEquivalenceIndex()
        index.build(self.root, exclude_patterns=self.exclude_patterns)

        plan = RefactorPlan()

        # Process file-level duplicates
        for group in index.find_duplicates():
            hash_val = group.hash
            # The shared package and the stubs of earlier runs are this engine's
            # own output; regrouping them would make re-runs rewrite them again.
            files = [f for f in group.files if not self._is_managed_file(f)]
            if len(files) < 2:
                continue
            canonical = self._select_canonical(files)

            # Extract symbols from canonical file
            symbols = self._extract_symbols(canonical)
            reason = self._skip_reason(canonical, symbols)
            if reason is not None:
                plan.skipped[hash_val] = reason
                logger.info("Skipping duplicate group %s (%s): %s", hash_val[:12], canonical, reason)
                continue

            plan.canonical_map[hash_val] = canonical
            plan.duplicates[hash_val] = [f for f in files if f != canonical]
            plan.affected_files.update(files)
            if symbols:
                plan.symbols[hash_val] = symbols

        logger.info(
            "Built refactoring plan: %d duplicate groups (%d skipped)",
            len(plan.duplicates),
            len(plan.skipped),
        )
        return plan

    def _is_inside_shared_module(self, path: Path) -> bool:
        return path.resolve().is_relative_to(self.shared_module.resolve())

    def _is_managed_file(self, path: Path) -> bool:
        """Return True for files this engine generates (shared modules and re-export stubs)."""
        if self._is_inside_shared_module(path):
            return True
        try:
            with path.open(encoding="utf-8") as handle:
                first_line = handle.readline()
        except (OSError, UnicodeDecodeError):
            return False
        return first_line.rstrip("\r\n") == _STUB_MARKER

    def _skip_reason(self, canonical: Path, symbols: list[SymbolInfo]) -> Optional[str]:
        """Return why a duplicate group must not be refactored, or None."""
        if len(symbols) < self.min_symbols:
            return f"{len(symbols)} top-level symbol(s), below min_symbols={self.min_symbols}"
        try:
            tree = ast.parse(canonical.read_text(encoding="utf-8"))
        except (OSError, SyntaxError, UnicodeDecodeError, ValueError) as e:
            return f"cannot parse canonical file: {e}"
        return _relocation_blocker(tree)

    def _select_canonical(self, files: list[Path]) -> Path:
        """Select the canonical file from a group of duplicates.

        Selection criteria (in order):
        1. Shortest path (prefer less nested)
        2. Lexicographic order (deterministic)

        Args:
            files: List of duplicate file paths.

        Returns:
            The selected canonical file path.
        """
        return sorted(files, key=lambda p: (len(str(p)), str(p)))[0]

    def _extract_symbols(self, file: Path) -> list[SymbolInfo]:
        """Extract symbols (functions, classes) from a file.

        Args:
            file: Path to the Python file.

        Returns:
            List of SymbolInfo for each top-level symbol.
        """
        try:
            source = file.read_text(encoding="utf-8")
            tree = ast.parse(source)
        except Exception as e:
            logger.warning("Could not parse %s: %s", file, e)
            return []

        symbols = []
        for node in tree.body:
            if isinstance(node, ast.FunctionDef):
                # Extract function source
                func_source = ast.unparse(node)
                func_hash = compute_ast_hash(func_source)

                symbols.append(
                    SymbolInfo(
                        name=node.name,
                        kind="function",
                        hash=func_hash,
                        source=func_source,
                    )
                )

            elif isinstance(node, ast.AsyncFunctionDef):
                func_source = ast.unparse(node)
                func_hash = compute_ast_hash(func_source)

                symbols.append(
                    SymbolInfo(
                        name=node.name,
                        kind="async_function",
                        hash=func_hash,
                        source=func_source,
                    )
                )

            elif isinstance(node, ast.ClassDef):
                class_source = ast.unparse(node)
                class_hash = compute_ast_hash(class_source)

                symbols.append(
                    SymbolInfo(
                        name=node.name,
                        kind="class",
                        hash=class_hash,
                        source=class_source,
                    )
                )

        return symbols

    # --------------------------------------------------
    # Phase 2: Execute refactoring
    # --------------------------------------------------
    def execute(self, plan: RefactorPlan, *, dry_run: bool = True) -> RefactorResult:
        """Execute the refactoring plan.

        A real run validates every generated shared module (compile, AST
        hash, subprocess import with the re-exported names) before it rewrites
        any duplicate. Any failure makes ``success`` False and rolls the tree
        back to its previous state (``rolled_back`` is then True).

        Args:
            plan: The refactoring plan to execute.
            dry_run: If True, don't actually modify files.

        Returns:
            RefactorResult with details of changes made.
        """
        result = RefactorResult(success=True, dry_run=dry_run)

        if not plan.duplicates:
            logger.info("No duplicates to refactor")
            return result

        try:
            # Phase 2a: Create shared module structure
            self._materialize_shared_module(plan, result, dry_run)

            # Phase 2b: Validate the shared modules before anything is rewritten
            if not dry_run and not result.errors:
                self._validate_refactoring(plan, result)

            # Phase 2c: Rewrite duplicate files
            if not result.errors:
                self._rewrite_duplicates(plan, result, dry_run)

        except Exception as e:
            logger.error("Refactoring failed: %s", e)
            result.errors.append(str(e))

        result.success = not result.errors
        if not result.success and not dry_run:
            logger.error("Refactoring failed with %d error(s); rolling back", len(result.errors))
            self.rollback(result)

        return result

    def _materialize_shared_module(self, plan: RefactorPlan, result: RefactorResult, dry_run: bool) -> None:
        """Create the shared module with canonical implementations.

        Args:
            plan: Refactoring plan with canonical mappings.
            result: Result object to update.
            dry_run: If True, don't create files.
        """
        if not dry_run:
            missing_dir = self.shared_module
            while not missing_dir.exists() and missing_dir.parent != missing_dir:
                result.dirs_created.append(missing_dir)
                missing_dir = missing_dir.parent
            self.shared_module.mkdir(parents=True, exist_ok=True)

            # Create __init__.py
            init_path = self.shared_module / "__init__.py"
            if not init_path.exists():
                init_content = '"""Shared canonical implementations (auto-generated)."""\n'
                self._write_text(init_path, init_content)
                result.files_created.append(init_path)

        for hash_val, canonical_file in plan.canonical_map.items():
            module_name = f"_{hash_val[:12]}"
            target = self.shared_module / f"{module_name}.py"

            if dry_run:
                logger.info("Would create: %s (from %s)", target, canonical_file)
                result.files_created.append(target)
            else:
                try:
                    source = canonical_file.read_text(encoding="utf-8")
                    content = self._render_shared_module(source, hash_val, canonical_file)

                    if target.exists():
                        # Same canonical file from an earlier run: reuse it, never clobber anything else.
                        if target.read_text(encoding="utf-8") != content:
                            result.errors.append(f"Refusing to overwrite existing {target} with different content")
                        continue

                    self._write_text(target, content)
                    result.files_created.append(target)
                    logger.info("Created: %s", target)

                except Exception as e:
                    result.errors.append(f"Failed to create {target}: {e}")

    def _display_path(self, path: Path) -> str:
        try:
            return path.resolve().relative_to(self.root.resolve()).as_posix()
        except ValueError:
            return str(path)

    def _render_shared_module(self, source: str, hash_val: str, canonical_file: Path) -> str:
        """Return the shared module text: the canonical source verbatim behind a comment header.

        The header is a comment so the module docstring and any ``from
        __future__`` import keep their required positions; a leading shebang or
        PEP 263 encoding declaration stays on its line.
        """
        lines = source.splitlines(keepends=True)
        keep = 0
        if lines and _CODING_COOKIE_RE.match(lines[0]):
            keep = 1
        elif len(lines) > 1 and lines[0].lstrip().startswith("#") and _CODING_COOKIE_RE.match(lines[1]):
            keep = 2  # a declaration on line 2 is honoured only after a comment-only line 1
        elif lines and lines[0].startswith("#!"):
            keep = 1
        header = (
            f"# Canonical implementation (hash: {hash_val[:16]}), generated by AutoRefactorEngine.\n"
            f"# Source: {self._display_path(canonical_file)}\n"
        )
        return "".join(lines[:keep]) + header + "".join(lines[keep:])

    def _rewrite_duplicates(self, plan: RefactorPlan, result: RefactorResult, dry_run: bool) -> None:
        """Rewrite duplicate files to import from shared module.

        Stops at the first failure; ``execute`` then rolls everything back.

        Args:
            plan: Refactoring plan with duplicate mappings.
            result: Result object to update.
            dry_run: If True, don't modify files.
        """
        for hash_val, files in plan.duplicates.items():
            module_name = f"_{hash_val[:12]}"

            if dry_run:
                for file in files:
                    logger.info("Would rewrite: %s → import from %s", file, module_name)
                    result.files_modified.append(file)
                continue

            try:
                stub = self._render_stub(module_name, plan.canonical_map[hash_val])
            except Exception as e:
                result.errors.append(f"Failed to render re-export stub for {module_name}: {e}")
                return

            for file in files:
                try:
                    self._rewrite_file_to_import(file, stub, hash_val, result)
                    logger.info("Rewrote: %s", file)
                except Exception as e:
                    result.errors.append(f"Failed to rewrite {file}: {e}")
                    return

    def _render_stub(self, module_name: str, canonical_file: Path) -> str:
        """Return the re-export stub that replaces each duplicate of a group.

        The stub keeps the module docstring and ``__future__`` imports and
        imports every top-level name of the (validated) shared module by
        explicit name, so private names, ``__all__`` and star imports behave as
        they did in the original file.
        """
        dotted = f"{self.package_name}.{module_name}"
        tree = ast.parse((self.shared_module / f"{module_name}.py").read_text(encoding="utf-8"))
        names = _module_exports(tree)

        lines = [
            _STUB_MARKER,
            f"# Canonical implementation: {dotted} (source: {self._display_path(canonical_file)})",
        ]
        if ast.get_docstring(tree, clean=False) is not None:
            # Unparsed in module position so it is emitted as a docstring.
            lines.append(ast.unparse(ast.Module(body=[tree.body[0]], type_ignores=[])))
        lines.extend(ast.unparse(stmt) for stmt in tree.body if _is_future_import(stmt))
        if names:
            lines.append(f"from {dotted} import (  # noqa: F401")
            lines.extend(f"    {name}," for name in names)
            lines.append(")")
        else:
            # Nothing to re-export, but the module body must still run once.
            lines.append(f"__import__({dotted!r})")

        stub = "\n".join(lines) + "\n"
        compile(stub, f"<re-export stub for {dotted}>", "exec", dont_inherit=True)
        return stub

    def _rewrite_file_to_import(self, path: Path, stub: str, hash_val: str, result: RefactorResult) -> None:
        """Replace a duplicate file with the re-export stub, keeping a backup for rollback.

        Args:
            path: Path to the file to rewrite.
            stub: Re-export stub text (see ``_render_stub``).
            hash_val: AST hash the file must still have (guards against a stale plan).
            result: Result object that records the backup and the modification.
        """
        if self._is_inside_shared_module(path):
            raise ValueError("refusing to rewrite a file inside the shared module")

        original = path.read_bytes()
        current_hash = compute_ast_hash(original.decode("utf-8"))
        if current_hash != hash_val:
            raise ValueError(f"file changed since the plan was built (hash {current_hash[:12]} != {hash_val[:12]})")

        result.backups[path] = original
        self._write_text(path, stub)
        result.files_modified.append(path)

    def _validate_refactoring(self, plan: RefactorPlan, result: RefactorResult) -> None:
        """Validate the generated shared modules before any duplicate is rewritten.

        Each shared module must compile (unlike ``ast.parse``, ``compile``
        enforces ``from __future__`` placement), keep the AST hash of its
        group, and import cleanly in a fresh interpreter with every name the
        re-export stubs will import from it.

        Args:
            plan: The refactoring plan.
            result: Result object to update with validation errors.
        """
        import_specs: list[str] = []
        for hash_val in plan.canonical_map:
            module_name = f"_{hash_val[:12]}"
            shared_file = self.shared_module / f"{module_name}.py"

            if not shared_file.exists():
                result.errors.append(f"Shared module not found: {shared_file}")
                continue

            try:
                source = shared_file.read_text(encoding="utf-8")
                compile(source, str(shared_file), "exec", dont_inherit=True)
                shared_hash = compute_ast_hash(source)

                if shared_hash != hash_val:
                    result.errors.append(f"Hash mismatch for {shared_file}: expected {hash_val[:12]}, got {shared_hash[:12]}")
                    continue

                names = _module_exports(ast.parse(source))
                import_specs.append(f"{self.package_name}.{module_name}=" + ",".join(names))

            except Exception as e:
                result.errors.append(f"Validation failed for {shared_file}: {e}")

        if import_specs and not result.errors:
            self._check_imports(import_specs, result)

    def _check_imports(self, import_specs: list[str], result: RefactorResult) -> None:
        """Import the shared modules in a subprocess (no bytecode written) and record failures."""
        argv = [sys.executable, "-B", "-c", _IMPORT_CHECK_SCRIPT, str(self.root.resolve())]
        try:
            subprocess.run(
                argv,
                input="\n".join(import_specs) + "\n",
                cwd=self.root,
                check=True,
                capture_output=True,
                text=True,
                timeout=_IMPORT_CHECK_TIMEOUT_S,
            )
        except subprocess.TimeoutExpired:
            result.errors.append(f"Import check of the shared modules timed out after {_IMPORT_CHECK_TIMEOUT_S:.0f}s")
        except subprocess.CalledProcessError as exc:
            stderr_lines = (exc.stderr or "").splitlines()
            failures = [line[len(_IMPORT_CHECK_PREFIX) :] for line in stderr_lines if line.startswith(_IMPORT_CHECK_PREFIX)]
            if not failures:
                failures = [f"exit code {exc.returncode}: " + (stderr_lines[-1] if stderr_lines else "no output")]
            result.errors.extend(f"Import check failed: {failure}" for failure in failures)

    @staticmethod
    def _write_text(path: Path, text: str) -> None:
        from transformation_portal.lux_depth_v3.io_atomic import atomic_write_bytes

        atomic_write_bytes(path, text.encode("utf-8"))

    # --------------------------------------------------
    # Utility methods
    # --------------------------------------------------
    def rollback(self, result: RefactorResult) -> None:
        """Rollback changes made by a refactoring execution.

        Restores every rewritten file from its backup, deletes the files the
        execution created and removes the shared-module directories it created
        when they are empty again. Safe to call more than once.

        Args:
            result: The RefactorResult from a previous execution.
        """
        if result.dry_run:
            logger.info("Nothing to rollback (was dry run)")
            return
        if result.rolled_back:
            logger.info("Already rolled back")
            return

        from transformation_portal.lux_depth_v3.io_atomic import atomic_write_bytes

        failures: list[str] = []
        for path, original in reversed(list(result.backups.items())):
            try:
                atomic_write_bytes(path, original)
                logger.info("Restored: %s", path)
            except OSError as e:
                failures.append(f"Rollback could not restore {path}: {e}")

        for path in reversed(result.files_created):
            try:
                path.unlink(missing_ok=True)
                logger.info("Deleted: %s", path)
            except OSError as e:
                failures.append(f"Rollback could not delete {path}: {e}")

        for directory in result.dirs_created:
            try:
                directory.rmdir()
            except OSError:
                logger.debug("Leaving directory in place (not empty or already gone): %s", directory)

        if failures:
            for failure in failures:
                logger.error(failure)
            result.errors.extend(failures)
            result.success = False
        else:
            result.rolled_back = True

    def preview(self, plan: RefactorPlan) -> str:
        """Generate a preview of what the refactoring will do.

        Args:
            plan: The refactoring plan.

        Returns:
            Human-readable preview string.
        """
        lines = [plan.summary(), "", "Actions:"]

        for hash_val, canonical_file in plan.canonical_map.items():
            module_name = f"_{hash_val[:12]}"
            lines.append(f"  CREATE: {self.shared_module / module_name}.py")
            lines.append(f"    Source: {canonical_file}")

            for dup in plan.duplicates.get(hash_val, []):
                lines.append(f"  REWRITE: {dup}")

        return "\n".join(lines)


class IncrementalRefactor:
    """Incremental refactoring for large codebases.

    This class provides methods for refactoring in smaller batches,
    useful for very large codebases or gradual migration.
    """

    def __init__(self, engine: AutoRefactorEngine):
        self.engine = engine

    def refactor_by_hash(self, plan: RefactorPlan, target_hash: str, *, dry_run: bool = True) -> RefactorResult:
        """Refactor only files matching a specific hash.

        Args:
            plan: Full refactoring plan.
            target_hash: The AST hash to refactor.
            dry_run: If True, don't modify files.

        Returns:
            RefactorResult for this specific hash.
        """
        # Create a filtered plan
        filtered_plan = RefactorPlan()

        if target_hash in plan.canonical_map:
            filtered_plan.canonical_map[target_hash] = plan.canonical_map[target_hash]
            filtered_plan.duplicates[target_hash] = plan.duplicates.get(target_hash, [])
            filtered_plan.symbols[target_hash] = plan.symbols.get(target_hash, [])
            filtered_plan.affected_files = set(filtered_plan.duplicates[target_hash])
            filtered_plan.affected_files.add(filtered_plan.canonical_map[target_hash])

        return self.engine.execute(filtered_plan, dry_run=dry_run)

    def refactor_batch(self, plan: RefactorPlan, batch_size: int = 5, *, dry_run: bool = True) -> list[RefactorResult]:
        """Refactor in batches of a specified size.

        Args:
            plan: Full refactoring plan.
            batch_size: Number of duplicate groups per batch.
            dry_run: If True, don't modify files.

        Returns:
            List of RefactorResult for each batch.
        """
        results = []
        hashes = list(plan.duplicates.keys())

        for i in range(0, len(hashes), batch_size):
            batch_hashes = hashes[i : i + batch_size]

            # Create batch plan
            batch_plan = RefactorPlan()
            for h in batch_hashes:
                batch_plan.canonical_map[h] = plan.canonical_map[h]
                batch_plan.duplicates[h] = plan.duplicates[h]
                batch_plan.symbols[h] = plan.symbols.get(h, [])
                batch_plan.affected_files.update(batch_plan.duplicates[h])
                batch_plan.affected_files.add(batch_plan.canonical_map[h])

            result = self.engine.execute(batch_plan, dry_run=dry_run)
            results.append(result)

            if not result.success:
                logger.warning("Batch %d failed, stopping", i // batch_size)
                break

        return results
