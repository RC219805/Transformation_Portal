"""Tests for the dependency-pinning validator."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from types import ModuleType

import pytest

pytestmark = pytest.mark.unit

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SCRIPT_PATH = PROJECT_ROOT / "scripts" / "validation" / "check_dependency_pinning.py"
REQUIREMENTS_DIR = PROJECT_ROOT / "requirements"


def _load_module() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_dependency_pinning", SCRIPT_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_pinned_lockfile_is_accepted(tmp_path: Path) -> None:
    module = _load_module()
    lockfile = tmp_path / "good.txt"
    lockfile.write_text(
        "# autogenerated\n"
        "aiofiles==25.1.0\n"
        "pydantic==2.10.0\n"
        "    # via fastapi\n"
        'uvicorn==0.46.0 ; python_version >= "3.11"\n',
        encoding="utf-8",
    )

    assert module.find_violations([lockfile]) == []


