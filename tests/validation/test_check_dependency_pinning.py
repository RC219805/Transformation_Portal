"""Tests for the dependency-pinning validator."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from types import ModuleType

import pytest

pytestmark = pytest.mark.unit

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SCRIPT_PATH = PROJECT_ROOT / "scripts" / "validation" / "check_dependency_pinning.py"
REQUIREMENTS_DIR = PROJECT_ROOT / "requirements"


def _load_module() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_dependency_pinning", SCRIPT_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_pinned_lockfile_is_accepted(tmp_path: Path) -> None:
    module = _load_module()
    lockfile = tmp_path / "good.txt"
    lockfile.write_text(
        "# autogenerated\n"
        "aiofiles==25.1.0\n"
        "pydantic==2.10.0\n"
        "    # via fastapi\n"
        'uvicorn==0.46.0 ; python_version >= "3.11"\n',
        encoding="utf-8",
    )

    assert module.find_violations([lockfile]) == []


def test_extras_pinned_with_equals_is_accepted(tmp_path: Path) -> None:
    module = _load_module()
    lockfile = tmp_path / "extras.txt"
    lockfile.write_text("coverage[toml]==7.13.5\n", encoding="utf-8")

    assert module.find_violations([lockfile]) == []


def test_hash_continuation_lines_are_ignored(tmp_path: Path) -> None:
    module = _load_module()
    lockfile = tmp_path / "hashed.txt"
    lockfile.write_text(
        "aiofiles==25.1.0 \\\n    --hash=sha256:abc123 \\\n    --hash=sha256:def456\n",
        encoding="utf-8",
    )

    assert module.find_violations([lockfile]) == []


def test_pip_option_lines_are_ignored(tmp_path: Path) -> None:
    module = _load_module()
    lockfile = tmp_path / "options.txt"
    lockfile.write_text(
        "-c constraints.txt\n-r base.in\n--index-url https://example.invalid/simple\naiofiles==25.1.0\n",
        encoding="utf-8",
    )

    assert module.find_violations([lockfile]) == []


@pytest.mark.parametrize(
    "operator",
    [">=", "<=", "~=", "!=", ">", "<"],
)
def test_unpinned_operator_is_rejected(tmp_path: Path, operator: str) -> None:
    module = _load_module()
    lockfile = tmp_path / "bad.txt"
    lockfile.write_text(f"somepkg{operator}1.0.0\n", encoding="utf-8")

    violations = module.find_violations([lockfile])

    assert len(violations) == 1
    assert operator in violations[0]
    assert "somepkg" in violations[0]


def test_bare_package_without_version_is_rejected(tmp_path: Path) -> None:
    module = _load_module()
    lockfile = tmp_path / "bare.txt"
    lockfile.write_text("somepkg\n", encoding="utf-8")

    violations = module.find_violations([lockfile])

    assert len(violations) == 1
    assert "no exact (==) pin" in violations[0]


def test_iter_lockfiles_excludes_constraints(tmp_path: Path) -> None:
    module = _load_module()
    (tmp_path / "base.txt").write_text("aiofiles==25.1.0\n", encoding="utf-8")
    (tmp_path / "constraints.txt").write_text("realesrgan>=9999.0.0\n", encoding="utf-8")

    paths = module.iter_lockfiles(tmp_path)

    assert [path.name for path in paths] == ["base.txt"]


def test_real_repository_lockfiles_are_pinned() -> None:
    """The shipped lockfiles must satisfy the contract."""
    module = _load_module()
    lockfiles = module.iter_lockfiles(REQUIREMENTS_DIR)

    assert lockfiles, "expected at least one compiled lockfile"
    assert module.find_violations(lockfiles) == []
