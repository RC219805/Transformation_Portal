@dataclass(frozen=True)
class _Parent:
    source_identity_sha256: str
    verification_entries: tuple


def _record_entries(paths):
    entries = {}
    token = runtime.identity._VERIFICATION_ENTRIES.set(entries)
    try:
        for path in paths:
            runtime.identity._record_verification_stat(path)
    finally:
        runtime.identity._VERIFICATION_ENTRIES.reset(token)
    return tuple(entries.values())


@pytest.fixture
def closure(tmp_path, monkeypatch):
    source = tmp_path / "source"
    source.mkdir()
    code = source / "processing.py"
    code.write_text("value = 1\n")
    wheel = tmp_path / "installed"
    wheel.mkdir()
    codec = wheel / "tifffile.py"
    codec.write_text("value = 1\n")
    helper = wheel / "codec_helper.py"
    helper.write_text("value = 1\n")
    state = SimpleNamespace(source=source, code=code, codec=codec, helper=helper, origin=codec, extra_files=[])

    def parent():
        return _Parent("a" * 64, _record_entries([source, code]))

    def spec(name):
        if name == "tifffile":
            return importlib.machinery.ModuleSpec(name, loader=None, origin=str(state.origin))
        return None

    def distribution(_name, **_kwargs):
        records = []
        for path in (codec, helper, *state.extra_files):
            digest, size = runtime.identity._hash_regular_file(path)
            records.append({"path": str(path), "sha256": digest, "size_bytes": size})
        runtime.identity._record_verification_stat(wheel)
        return {"name": "tifffile", "files": records}

    def imports(_names):
        return {
            "tifffile": {
                "origin": str(state.origin),
                "sha256": hashlib.sha256(state.origin.read_bytes()).hexdigest(),
            }
        }

    monkeypatch.setattr(runtime.identity, "prepare_parent_output_runtime_identity", parent)
    monkeypatch.setattr(runtime.identity, "verify_parent_output_runtime_identity", lambda _parent: True)
    monkeypatch.setattr(runtime.identity, "_installed_distribution_index", lambda: {"tifffile": (object(), "1")})
    monkeypatch.setattr(runtime.identity, "_distribution_record", distribution)
    monkeypatch.setattr(runtime.identity, "_import_environment_payload", imports)
    monkeypatch.setattr(runtime.importlib.util, "find_spec", spec)
    return state


def test_shadow_codec_cannot_borrow_installed_distribution_authority(closure, tmp_path):
    closure.origin = tmp_path / "shadow_tifffile.py"
    closure.origin.write_text("value = 1\n")
    with pytest.raises(RuntimeError, match="outside its materialized distribution"):
        runtime.PhotographyRuntime()


def test_actual_codec_bytes_change_identity_and_invalidate_materialized_runtime(closure):
    prepared = runtime.PhotographyRuntime()
    closure.codec.write_text("value = 2\n")
    with pytest.raises(RuntimeError, match="codec import identity changed"):
        prepared.verify()
    assert runtime.PhotographyRuntime().sha256 != prepared.sha256


