    state = SimpleNamespace(source=source, code=code, codec=codec, helper=helper, origin=codec, extra_files=[])

    def parent():
        return _Parent("a" * 64, _record_entries([source, code]))

    def spec(name):
        if name == "tifffile":
            return importlib.machinery.ModuleSpec(name, loader=None, origin=str(state.origin))
        return None

    def distribution(_name, **_kwargs):
        records = []
        for path in (codec, helper, *state.extra_files):
            digest, size = runtime.identity._hash_regular_file(path)
            records.append({"path": str(path), "sha256": digest, "size_bytes": size})
        runtime.identity._record_verification_stat(wheel)
        return {"name": "tifffile", "files": records}

    def imports(_names):
        return {
            "tifffile": {
                "origin": str(state.origin),
                "sha256": hashlib.sha256(state.origin.read_bytes()).hexdigest(),
            }
        }

    monkeypatch.setattr(runtime.identity, "prepare_parent_output_runtime_identity", parent)
    monkeypatch.setattr(runtime.identity, "verify_parent_output_runtime_identity", lambda _parent: True)
    monkeypatch.setattr(runtime.identity, "_installed_distribution_index", lambda: {"tifffile": (object(), "1")})
    monkeypatch.setattr(runtime.identity, "_distribution_record", distribution)
    monkeypatch.setattr(runtime.identity, "_import_environment_payload", imports)
    monkeypatch.setattr(runtime.importlib.util, "find_spec", spec)
    return state


