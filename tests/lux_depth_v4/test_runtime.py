def _source_cache(source, *, replacement=None, optimization=0):
    cache = Path(importlib.util.cache_from_source(str(source), optimization="" if optimization == 0 else str(optimization)))
    py_compile.compile(str(source), cfile=str(cache), doraise=True, optimize=optimization)
    if replacement is not None:
        code = compile(replacement, str(source), "exec", dont_inherit=True, optimize=optimization)
        cache.write_bytes(cache.read_bytes()[:16] + marshal.dumps(code))
    return cache


@pytest.mark.parametrize("optimization", [0, 1, 2])
def test_legitimate_source_bytecode_churn_preserves_runtime_identity(closure, optimization):
    prepared = runtime.PhotographyRuntime()
    cache = _source_cache(closure.code, optimization=optimization)
    prepared.verify()
    cache.write_bytes(cache.read_bytes())
    prepared.verify()


def test_forged_timestamp_valid_bytecode_is_rejected_before_lazy_import(closure, monkeypatch):
    prepared = runtime.PhotographyRuntime()
    _source_cache(closure.code, replacement="value = 999\n")

    def forbidden_loads(*_args, **_kwargs):
        pytest.fail("Runtime verification must never unmarshal untrusted bytecode")

    monkeypatch.setattr(runtime.marshal, "loads", forbidden_loads)
    assert closure.code.read_text() == "value = 1\n"
    with pytest.raises(RuntimeError, match="cached bytecode differs from its source"):
        prepared.verify()


def test_wheel_script_lexical_source_filename_is_verified(closure, tmp_path, monkeypatch):
    site_packages = tmp_path / "environment" / "site-packages"
    site_packages.mkdir(parents=True)
    monkeypatch.syspath_prepend(str(site_packages))
    cache = _source_cache(closure.code)
    filename = str(site_packages / ".." / ".." / "source" / "processing.py")
    assert Path(filename).resolve() == closure.code
    code = compile(closure.code.read_bytes(), filename, "exec", dont_inherit=True, optimize=0)
    cache.write_bytes(cache.read_bytes()[:16] + marshal.dumps(code))
    prepared = runtime.PhotographyRuntime()
    prepared.verify()


def test_rewritten_verified_bytecode_must_revalidate_its_payload(closure):
    cache = _source_cache(closure.code)
    prepared = runtime.PhotographyRuntime()
    prepared.verify()
    original_size = cache.stat().st_size
    _source_cache(closure.code, replacement="value = 2\n")
    assert cache.stat().st_size == original_size
    with pytest.raises(RuntimeError, match="cached bytecode differs from its source"):
        prepared.verify()


def test_oversized_bytecode_is_rejected_before_read_or_compilation(closure, monkeypatch):
    prepared = runtime.PhotographyRuntime()
    cache = _source_cache(closure.code)
    with cache.open("wb") as handle:
        handle.truncate(runtime._MAX_BYTECODE_BYTES + 1)

    def forbidden_compile(*_args, **_kwargs):
        pytest.fail("Oversized bytecode must be rejected before source compilation")

    monkeypatch.setattr(runtime, "compile", forbidden_compile, raising=False)
    with pytest.raises(RuntimeError, match="regular-file bound"):
        prepared.verify()


def test_oversized_bytecode_source_is_rejected_before_compilation(closure, monkeypatch):
    cache = _source_cache(closure.code)
    monkeypatch.setattr(runtime, "_MAX_BYTECODE_SOURCE_BYTES", 1)
    with pytest.raises(RuntimeError, match="regular-file bound"):
        runtime._directory_inventory(cache.parent)
