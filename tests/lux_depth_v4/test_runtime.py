def _source_cache(source, *, replacement=None, optimization=0):
    cache = Path(importlib.util.cache_from_source(str(source), optimization="" if optimization == 0 else str(optimization)))
    py_compile.compile(str(source), cfile=str(cache), doraise=True, optimize=optimization)
    if replacement is not None:
        code = compile(replacement, str(source), "exec", dont_inherit=True, optimize=optimization)
        cache.write_bytes(cache.read_bytes()[:16] + marshal.dumps(code))
    return cache


